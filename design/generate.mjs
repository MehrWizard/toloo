import { readFileSync, readdirSync, writeFileSync, existsSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const repo = path.dirname(here);
const contract = JSON.parse(readFileSync(path.join(here, "contract.json"), "utf8"));
const check = process.argv.includes("--check");
const outputs = new Map();

function emit(relativePath, content) {
    outputs.set(path.join(repo, relativePath), content);
}

function colors(scheme) {
    return { ...contract.colors.common, ...contract.colors[scheme] };
}

function slintColor(value) {
    return value;
}

function themeSlint() {
    const c = colors("native");
    return `// Generated by design/generate.mjs — edit design/contract.json instead.

export global Theme {
    out property <color> bg: ${slintColor(c.bg)};
    out property <color> bg-raised: ${slintColor(c.bgRaised)};
    out property <color> surface: ${slintColor(c.surface)};
    out property <color> surface-2: ${slintColor(c.surface2)};
    out property <color> surface-3: ${slintColor(c.surface3)};
    out property <color> border: ${slintColor(c.border)};
    out property <color> border-strong: ${slintColor(c.borderStrong)};
    out property <color> accent: ${slintColor(c.accent)};
    out property <color> accent-strong: ${slintColor(c.accentStrong)};
    out property <color> accent-ink: ${slintColor(c.accentInk)};
    out property <color> text: ${slintColor(c.text)};
    out property <color> text-2: ${slintColor(c.text2)};
    out property <color> muted: ${slintColor(c.muted)};
    out property <color> success: ${slintColor(c.success)};
    out property <color> warn: ${slintColor(c.warn)};
    out property <color> danger: ${slintColor(c.danger)};
    out property <color> bubble-mine: ${slintColor(c.bubbleMine)};
    out property <color> bubble-mine-border: ${slintColor(c.bubbleMineBorder)};

    out property <length> radius: ${contract.radii.radius}px;
    out property <length> radius-sm: ${contract.radii.radiusSmall}px;
    out property <length> sidebar-width: ${contract.layout.sidebarWidth}px;
    out property <length> rail-width: ${contract.layout.railWidth}px;
    out property <length> header-height: ${contract.layout.headerHeight}px;
    out property <length> settings-width: ${contract.layout.settingsWidth}px;
    out property <length> touch-target: ${contract.layout.touchTarget}px;

    out property <length> font-xs: ${contract.typography.xs}px;
    out property <length> font-sm: ${contract.typography.sm}px;
    out property <length> font-ui: ${contract.typography.ui}px;
    out property <length> font-title: ${contract.typography.title}px;
    out property <length> font-brand: ${contract.typography.brand}px;

    out property <[color]> avatar-palette: [
${contract.avatarPalette.map((color) => `        ${slintColor(color)}`).join(",\n")}
    ];
}
`;
}

function copySlint() {
    const properties = contract.settings
        .map(
            (section) =>
                `    out property <string> ${section.id}: ${JSON.stringify(section.title)};`,
        )
        .join("\n");
    return `// Generated by design/generate.mjs — edit design/contract.json instead.

export global SettingsCopy {
${properties}
}
`;
}

function designCss() {
    const c = colors("web");
    const vars = {
        bg: c.bg,
        "bg-raised": c.bgRaised,
        panel: c.surface,
        "panel-2": c.surface2,
        "panel-3": c.surface3,
        line: c.border,
        "line-strong": c.borderStrong,
        accent: c.accent,
        "accent-strong": c.accentStrong,
        "accent-ink": c.accentInk,
        text: c.text,
        "text-soft": c.text2,
        muted: c.muted,
        faint: c.muted,
        success: c.success,
        warn: c.warn,
        danger: c.danger,
        "bubble-mine": c.bubbleMine,
        "bubble-mine-border": c.bubbleMineBorder,
        radius: `${contract.radii.radius}px`,
        "radius-sm": `${contract.radii.radiusSmall}px`,
        "sidebar-width": `${contract.layout.sidebarWidth}px`,
        "rail-width": `${contract.layout.railWidth}px`,
        "header-height": `${contract.layout.headerHeight}px`,
        "settings-width": `${contract.layout.settingsWidth}px`,
        "touch-target": `${contract.layout.touchTarget}px`,
        "font-xs": `${contract.typography.xs}px`,
        "font-sm": `${contract.typography.sm}px`,
        "font-ui": `${contract.typography.ui}px`,
        "font-title": `${contract.typography.title}px`,
        "font-brand": `${contract.typography.brand}px`,
    };
    for (const [key, value] of Object.entries(vars)) {
        vars[key] = value;
    }
    contract.avatarPalette.forEach((color, index) => {
        vars[`avatar-${index}`] = color;
    });
    const declarations = Object.entries(vars)
        .map(([key, value]) => `    --${key}: ${value};`)
        .join("\n");
    return `/* Generated by design/generate.mjs — edit design/contract.json instead. */
:root {
    color-scheme: dark;
${declarations}
}
`;
}

function designTs() {
    return `// Generated by design/generate.mjs — edit design/contract.json instead.

export const BREAKPOINTS = ${JSON.stringify(contract.breakpoints, null, 4)} as const;
export const LAYOUT = ${JSON.stringify(contract.layout, null, 4)} as const;
export const AVATAR_PALETTE = ${JSON.stringify(contract.avatarPalette, null, 4)} as const;
export const SETTINGS_SECTIONS = ${JSON.stringify(contract.settings, null, 4)} as const;
export type SettingsSectionId = (typeof SETTINGS_SECTIONS)[number]["id"];
`;
}

function cleanIcon(svg) {
    return svg
        .replace(/\s+width="24"/, "")
        .replace(/\s+height="24"/, "")
        .replace(/#fff(?:fff)?/g, "currentColor")
        .replace(/>\s+</g, "><")
        .trim();
}

function iconsTs() {
    const dir = path.join(here, "icons");
    const files = new Map(
        readdirSync(dir)
            .filter((name) => name.endsWith(".svg"))
            .map((name) => [name.slice(0, -4), name]),
    );
    for (const name of contract.icons) {
        if (!files.has(name)) {
            throw new Error(`design/icons/${name}.svg is missing`);
        }
    }
    const body = contract.icons
        .map((name) => {
            const svg = cleanIcon(readFileSync(path.join(dir, files.get(name)), "utf8"));
            return `    ${name}: ${JSON.stringify(svg)}`;
        })
        .join(",\n");
    return `// Generated by design/generate.mjs — edit design/icons instead.

export const ICONS = {
${body}
} as const;

export type IconName = keyof typeof ICONS;
`;
}

emit("toloo-app/ui/theme.slint", themeSlint());
emit("toloo-app/ui/design-copy.slint", copySlint());
emit("toloo-web/src/generated/design.css", designCss());
emit("toloo-web/src/generated/design.ts", designTs());
if (existsSync(path.join(here, "icons"))) {
    emit("toloo-web/src/generated/icons.ts", iconsTs());
}

let failed = false;
for (const [file, content] of outputs) {
    if (check) {
        const current = existsSync(file) ? readFileSync(file, "utf8") : "";
        if (current !== content) {
            console.error(`out of date: ${path.relative(repo, file)}`);
            failed = true;
        }
    } else {
        writeFileSync(file, content);
        console.log(`generated ${path.relative(repo, file)}`);
    }
}
if (failed) {
    console.error("Run: node design/generate.mjs");
    process.exit(1);
}
